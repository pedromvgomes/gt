func TestResolveProfileExpandsHomeAndSortsVariables(t *testing.T) {
	home, err := os.UserHomeDir()
	if err != nil {
		t.Skip("no home directory")
	}
	profiles := []config.Profile{{Name: "p", Match: []string{"*"}, Env: map[string]string{
		"ZED_HOME":          "~",
		"CODEX_HOME":        "$HOME/.codex",
		"CLAUDE_CONFIG_DIR": "~/.claude-personal",
		"OPAQUE":            "not-a-path",
	}}}
	got, err := setauth.ResolveProfile(profiles, "any", "", false)
	if err != nil {
		t.Fatalf("ResolveProfile() error = %v", err)
	}
	want := []setauth.EnvVar{
		{Name: "CLAUDE_CONFIG_DIR", Value: filepath.Join(home, ".claude-personal")},
		{Name: "CODEX_HOME", Value: filepath.Join(home, ".codex")},
		{Name: "OPAQUE", Value: "not-a-path"},
		{Name: "ZED_HOME", Value: home},
	}
	if !reflect.DeepEqual(got.Env, want) {
		t.Fatalf("ResolveProfile().Env = %#v, want %#v", got.Env, want)
	}
}

// Retrofitting an existing clone: 'gt set-auth' with no --user recovers the
// identity from the .envrc gt already wrote, so it needs no flags and asks
// nothing, and a second run is a no-op.
func TestRunRetrofitsExistingEnvrcWithoutAskingForUser(t *testing.T) {
	root := makeManagedRoot(t)
	envrcPath := filepath.Join(root, ".envrc")
	if err := os.WriteFile(envrcPath, []byte(baseEnvrc), 0o600); err != nil {
		t.Fatal(err)
	}
	opts := setauth.Options{
		CWD:      root,
		Profiles: []config.Profile{{Name: "personal", Match: []string{"*"}, Env: map[string]string{"CODEX_HOME": "/p/.codex"}}},
		Yes:      true,
	}
	newRunner := func() *fakeCommandRunner {
		return &fakeCommandRunner{
			paths: map[string]bool{"direnv": true},
			responses: map[string]setauthResult{
				"git remote get-url origin": {stdout: "git@github.com:acme/thing.git\n"},
			},
		}
	}

	runner := newRunner()
	// Non-interactive: a prompt here would be an error, which is the point.
	if err := setauth.Run(context.Background(), runner, quietUI(), opts); err != nil {
		t.Fatalf("Run() error = %v", err)
	}
	if runner.hasCall("gh api user --jq .login") {
		t.Fatalf("calls = %#v, want no gh lookup", runner.calls)
	}
	data, err := os.ReadFile(envrcPath)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(data), `export CODEX_HOME="/p/.codex"`) {
		t.Fatalf(".envrc = %q", string(data))
	}
	if !strings.Contains(string(data), "gh auth token --user pedromvgomes") {
		t.Fatalf(".envrc lost the gh user: %q", string(data))
	}

	// Idempotence: the second run changes nothing and reports it.
	before := string(data)
	out := &strings.Builder{}
	printer := &ui.UI{In: strings.NewReader(""), Out: out, Err: ioDiscard{}}
	if err := setauth.Run(context.Background(), newRunner(), printer, opts); err != nil {
		t.Fatalf("second Run() error = %v", err)
	}
	after, err := os.ReadFile(envrcPath)
	if err != nil {
		t.Fatal(err)
	}
	if string(after) != before {
		t.Fatalf("second run rewrote .envrc:\n%q\n%q", before, string(after))
	}
	if !strings.Contains(out.String(), "already up to date") {
		t.Fatalf("second run output = %q, want 'already up to date'", out.String())
	}
}

// A repository that matches nothing must keep the exact bytes it has, so
// running set-auth across every existing clone rewrites none of them.
func TestRunLeavesNonOptedInEnvrcByteIdentical(t *testing.T) {
	root := makeManagedRoot(t)
	envrcPath := filepath.Join(root, ".envrc")
	if err := os.WriteFile(envrcPath, []byte(baseEnvrc), 0o600); err != nil {
		t.Fatal(err)
	}
	runner := &fakeCommandRunner{
		paths: map[string]bool{"direnv": true},
		responses: map[string]setauthResult{
			"git remote get-url origin": {stdout: "git@github.com:other/thing.git\n"},
		},
	}
	err := setauth.Run(context.Background(), runner, quietUI(), setauth.Options{
		CWD:      root,
		Profiles: []config.Profile{{Name: "work", Match: []string{"github.com:acme/*"}, Env: map[string]string{"CODEX_HOME": "/w"}}},
	})
	if err != nil {
		t.Fatalf("Run() error = %v", err)
	}
	data, err := os.ReadFile(envrcPath)
	if err != nil {
		t.Fatal(err)
	}
	if string(data) != baseEnvrc {
		t.Fatalf(".envrc = %q, want it untouched", string(data))
	}
}
