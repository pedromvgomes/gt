type setauthResult struct {
	stdout string
	stderr string
	exit   int
	err    error
}

type fakeCommandRunner struct {
	calls     [][]string
	paths     map[string]bool
	responses map[string]setauthResult
	env       map[string]string
	goos      string
}

func (f *fakeCommandRunner) LookPath(file string) (string, error) {
	if f.paths[file] {
		return "/usr/bin/" + file, nil
	}
	return "", errors.New("not found")
}

func (f *fakeCommandRunner) Run(_ context.Context, _ string, name string, args ...string) (setauth.Result, error) {
	call := append([]string{name}, args...)
	f.calls = append(f.calls, call)
	key := strings.Join(call, " ")
	if result, ok := f.responses[key]; ok {
		return setauth.Result{Stdout: result.stdout, Stderr: result.stderr, Exit: result.exit}, result.err
	}
	return setauth.Result{}, nil
}

func (f *fakeCommandRunner) Env(name string) string {
	return f.env[name]
}

func (f *fakeCommandRunner) GOOS() string {
	if f.goos != "" {
		return f.goos
	}
	return "linux"
}

func (f *fakeCommandRunner) hasCall(want string) bool {
	for _, call := range f.calls {
		if strings.Join(call, " ") == want {
			return true
		}
	}
	return false
}

func TestResolveProfileMatchesRepoURLInOrder(t *testing.T) {
	profiles := []config.Profile{
		{Name: "work", Match: []string{"github.com:acme/*"}, Env: map[string]string{"CLAUDE_CONFIG_DIR": "/w"}},
		{Name: "catch-all", Match: []string{"*"}, Env: map[string]string{"CLAUDE_CONFIG_DIR": "/c"}},
	}
	cases := map[string]struct {
		url  string
		want string
	}{
		"first match wins":            {"git@github.com:acme/thing.git", "work"},
		"falls through to catch-all":  {"git@github.com:other/thing.git", "catch-all"},
		"no origin matches catch-all": {"", "catch-all"},
	}
	for name, tc := range cases {
		t.Run(name, func(t *testing.T) {
			got, err := setauth.ResolveProfile(profiles, tc.url, "", false)
			if err != nil {
				t.Fatalf("ResolveProfile() error = %v", err)
			}
			if got.Name != tc.want {
				t.Fatalf("ResolveProfile() = %q, want %q", got.Name, tc.want)
			}
		})
	}
}

// A profile with no match patterns is inert: it exists only to be named.
func TestResolveProfileIgnoresUnmatchedProfiles(t *testing.T) {
	profiles := []config.Profile{
		{Name: "personal", Env: map[string]string{"CODEX_HOME": "/p"}},
	}
	got, err := setauth.ResolveProfile(profiles, "git@github.com:acme/thing.git", "", false)
	if err != nil {
		t.Fatalf("ResolveProfile() error = %v", err)
	}
	if !got.Empty() {
		t.Fatalf("ResolveProfile() = %#v, want empty", got)
	}
	got, err = setauth.ResolveProfile(profiles, "", "personal", false)
	if err != nil {
		t.Fatalf("ResolveProfile() error = %v", err)
	}
	if got.Name != "personal" || len(got.Env) != 1 {
		t.Fatalf("ResolveProfile() = %#v, want the named profile", got)
	}
}

