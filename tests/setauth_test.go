// baseEnvrc is the exact content gt emitted before profiles existed. Every
// repository that has not opted in must keep producing these bytes, or the
// next set-auth run rewrites every existing clone.
const baseEnvrc = `# Auto-generated by gt set-auth.
# Scopes GH_TOKEN to gh user 'pedromvgomes' so 'gh pr create' etc.
# authenticate as pedromvgomes regardless of 'gh auth switch'.
export GH_TOKEN="$(gh auth token --user pedromvgomes)"
`

func TestEnvrcContentWithoutProfileIsUnchanged(t *testing.T) {
	got, err := setauth.EnvrcContent("pedromvgomes", setauth.Profile{})
	if err != nil {
		t.Fatalf("EnvrcContent() error = %v", err)
	}
	if got != baseEnvrc {
		t.Fatalf("EnvrcContent() = %q, want %q", got, baseEnvrc)
	}
}

// A profile that resolved to no variables is the same case as no profile at
// all: a name alone must not perturb the file.
func TestEnvrcContentWithNamedButEmptyProfileIsUnchanged(t *testing.T) {
	got, err := setauth.EnvrcContent("pedromvgomes", setauth.Profile{Name: "personal"})
	if err != nil {
		t.Fatalf("EnvrcContent() error = %v", err)
	}
	if got != baseEnvrc {
		t.Fatalf("EnvrcContent() = %q, want %q", got, baseEnvrc)
	}
}

func TestEnvrcContentWithProfile(t *testing.T) {
	profile := setauth.Profile{Name: "personal", Env: []setauth.EnvVar{
		{Name: "CLAUDE_CONFIG_DIR", Value: "/home/p/.claude-personal"},
		{Name: "CODEX_HOME", Value: "/home/p/.codex"},
	}}
	got, err := setauth.EnvrcContent("pedromvgomes", profile)
	if err != nil {
		t.Fatalf("EnvrcContent() error = %v", err)
	}
	want := baseEnvrc + `
# Profile 'personal' from the gt config. Pins the environment that tooling launched
# from this checkout resolves, so it does not depend on the shell it started in.
export CLAUDE_CONFIG_DIR="/home/p/.claude-personal"
export CODEX_HOME="/home/p/.codex"
`
	if got != want {
		t.Fatalf("EnvrcContent() = %q, want %q", got, want)
	}
}

// Profile values are arbitrary strings interpolated into export VAR="...", so
// the characters the shell still reads inside double quotes are escaped.
func TestEnvrcContentEscapesProfileValues(t *testing.T) {
	profile := setauth.Profile{Name: "odd", Env: []setauth.EnvVar{
		{Name: "TRICKY", Value: "a\"b$c`d\\e"},
	}}
	got, err := setauth.EnvrcContent("pedromvgomes", profile)
	if err != nil {
		t.Fatalf("EnvrcContent() error = %v", err)
	}
	want := "export TRICKY=\"a\\\"b\\$c\\`d\\\\e\"\n"
	if !strings.Contains(got, want) {
		t.Fatalf("EnvrcContent() = %q, missing %q", got, want)
	}
}

